"""
Doksmith Release Notes Engine: Markdown Sanitization & Document Builder.
ATM (Amati, Tiru, Modifikasi): Clean formatting, structured sections, and clickable commit logs.
"""

import re
from typing import List
from git_collector import GitCommit

# Matches all native Unicode emojis to keep changelog clean and formal
UNICODE_EMOJI_PATTERN = re.compile(
    r"[\U00010000-\U0010ffff]|[\u2600-\u27BF]|[\u2300-\u23FF]|[\u2B50]",
    flags=re.UNICODE,
)


class ChangelogBuilder:
    """Builds and sanitizes the final GitHub release document."""

    @staticmethod
    def strip_emojis(content: str) -> str:
        if not content:
            return ""
        return UNICODE_EMOJI_PATTERN.sub("", content).strip()

    @classmethod
    def assemble_full_changelog(cls, commits: List[GitCommit], repo_url: str) -> str:
        if not commits:
            return "_No commit history found._"
        return "\n".join(c.to_markdown(repo_url) for c in commits)

    @classmethod
    def assemble_release_document(
        cls,
        summary_markdown: str,
        commits: List[GitCommit],
        repo_url: str,
        provider_name: str,
        model_name: str,
    ) -> str:
        clean_summary = cls.strip_emojis(summary_markdown)
        changelog_section = cls.assemble_full_changelog(commits, repo_url)

        return (
            f"{clean_summary}\n\n"
            f"--------\n\n"
            f"## Full Changelog\n\n"
            f"{changelog_section}\n\n"
            f"--------\n\n"
            f"*Generated by Doksmith Release Notes Engine ({provider_name}: `{model_name}`)*\n"
        )
