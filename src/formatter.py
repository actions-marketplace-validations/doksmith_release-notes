import re


class MarkdownFormatter:
    """Cleans and standardizes markdown output for release notes."""

    # Unicode emoji pattern to sanitize native emojis if present
    EMOJI_PATTERN = re.compile(
        "["
        "\U0001F600-\U0001F64F"  # emoticons
        "\U0001F300-\U0001F5FF"  # symbols & pictographs
        "\U0001F680-\U0001F6FF"  # transport & map symbols
        "\U0001F1E0-\U0001F1FF"  # flags
        "\U00002702-\U000027B0"
        "\U000024C2-\U0001F251"
        "]+",
        flags=re.UNICODE,
    )

    @classmethod
    def sanitize(cls, text: str) -> str:
        """Strip native unicode emojis and normalize linebreaks."""
        cleaned = cls.EMOJI_PATTERN.sub("", text)
        # Normalize double blank lines
        cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
        return cleaned.strip()

    @classmethod
    def append_footer(cls, text: str, provider_name: str, model_name: str) -> str:
        """Attach concise provenance footer."""
        footer = f"\n\n---\n*Generated by Doksmith Release Notes ({provider_name}: `{model_name}`)*"
        return text + footer
